; --- ТЕСТ 42: СИСТЕМНЫЙ ТAЙМЕР (INT 08h) И КAНОНИЧЕСКИЙ ВOЗВРAТ IRET ---
X86_T42
        db      $BC, $00, $10           ; mov sp, 0x1000 
        db      $CD, $08                ; int 0x08       
        db      $F4                     ; hlt
X86_T42_E

; --- ТЕСТ 43: ИНТЕРAКТИВНЫЙ ОПРOС КЛAВИAТУРЫ BIOS (INT 16h) ---
X86_T43
        db      $B4, $01                ; mov ah, 0x01   
        db      $CD, $16                ; int 0x16       
        db      $B4, $00                ; mov ah, 0x00   
        db      $CD, $16                ; int 0x16       
        db      $F4                     ; hlt
X86_T43_E

; --- ТЕСТ 44: 8-БИТНОЕ ЗНAКOВOЕ УМНOЖЕНИЕ И ДЕЛЕНИЕ (IMUL / IDIV AL) ---
X86_T44
        db      $B0, $FB                ; mov al, -5     (AL = 0xFB)
        db      $B1, $04                ; mov cl, 4      (CL = 0x04)
        db      $F6, $E9                ; imul cl        (AX = AL * CL = -20 = 0xFFEC)
        db      $B8, $F6, $FF           ; mov ax, -10    (AX = 0xFFF6)
        db      $B1, $03                ; mov cl, 3      (CL = 0x03)
        db      $F6, $F9                ; idiv cl        (AL = Частное -3 = 0xFD, AH = Остаток -1 = 0xFF)
        db      $F4                     ; hlt
X86_T44_E

; --- ТЕСТ 45: ВАЛИДАЦИЯ СЛОЖНЫХ ЗНАКОВЫХ ПЕРЕХОДОВ (JG / JLE) ---
X86_T45
        db      $B0, $05                ; mov al, 5
        db      $B1, $03                ; mov cl, 3
        db      $3A, $C1                ; cmp al, cl     (5 > 3. ZF=0, SF=OF)
        db      $7F, $02                ; jg .PassedJG   
        db      $F4                     ; hlt            
.PassedJG
        db      $3A, $C8                ; cmp cl, al     (3 < 5. ZF=0, SF!=OF)
        db      $7E, $02                ; jle .PassedJLE 
        db      $F4                     ; hlt            
.PassedJLE
        db      $F4                     ; hlt            
X86_T45_E

; --- ТЕСТ 46: ВАЛИДАЦИЯ СЛОЖНЫХ ЗНАКОВЫХ ПЕРЕХОДОВ (JGE / JL) ---
X86_T46
        db      $B0, $FB                ; mov al, -5     (0xFB)
        db      $B1, $FD                ; mov cl, -3     (0xFD)
        db      $3A, $C1                ; cmp al, cl     (-5 < -3. ZF=0, SF!=OF)
        db      $7C, $02                ; jl .PassedJL   
        db      $F4                     ; hlt
.PassedJL
        db      $3A, $C8                ; cmp cl, al     (-3 >= -5. ZF=0, SF=OF)
        db      $7D, $02                ; jge .PassedJGE 
        db      $F4                     ; hlt
.PassedJGE
        db      $F4                     ; hlt            
X86_T46_E


; --- ТЕСТ 47: ВАЛИДАЦИЯ СOСТAВНOЙ АДРЕСАЦИИ БЕЗ СМЕЩЕНИЯ (mod=00) -> [BX+SI] ---
X86_T47
        db      $B8, $00, $20           ; mov ax, 0x2000
        db      $8E, $D8                ; mov ds, ax     (База данных DS = 0x2000)
        db      $BB, $00, $01           ; mov bx, 0x0100 
        db      $BE, $05, $00           ; mov si, 0x0005 ; Точный индекс
        db      $8B, $00                ; mov ax, [bx+si]; Опкод $8B с байтом ModR/M=$00 -> Чтение из DS:[BX+SI]
        db      $F4                     ; hlt            
X86_T47_E

; --- ТЕСТ 48: ВАЛИДАЦИЯ АДРЕСАЦИИ С 8-БИТНЫМ СМЕЩЕНИЕМ (mod=01) -> [BP+DI+Disp8] ---
X86_T48
        db      $B8, $00, $30           ; mov ax, 0x3000
        db      $8E, $D0                ; mov ss, ax     (База SS = 0x3000)
        db      $BD, $00, $01           ; mov bp, 0x0100 
        db      $BF, $02, $00           ; mov di, 0x0002 
        db      $8B, $43, $10           ; mov ax, [bp+di+0x10] ; ModR/M=$43, Disp8=$10 -> Чтение из SS:[BP+DI+16]
        db      $F4                     ; hlt            
X86_T48_E

; --- ТЕСТ 49: ВАЛИДАЦИЯ АДРЕСАЦИИ С 16-БИТНЫМ СМЕЩЕНИЕМ (mod=10) -> [SI+Disp16] ---
X86_T49
        db      $B8, $00, $20           ; mov ax, 0x2000
        db      $8E, $D8                ; mov ds, ax     (DS = 0x2000)
        db      $BE, $00, $01           ; mov si, 0x0100 
        db      $8B, $84, $00, $10      ; mov ax, [si+0x1000] ; ModR/M=$84, Disp16=$1000 -> Чтение из DS:[SI+4096]
        db      $F4                     ; hlt            
X86_T49_E

; --- ТЕСТ 50: ВАЛИДАЦИЯ УПРАВЛЕНИЯ ФЛАГОМ ЗАПРЕТА/РАЗРЕШЕНИЯ ПРЕРЫВАНИЙ ---
X86_T50
        db      $FA                     ; cli            (Флаг IF сбрасывается в 0, прерывания запрещены)
