; --- ОБРАБОТЧИК: LOOP Rel8 (Опкод $E2) ---
Op_LOOP_Rel8:
        PUSH    AF
        PUSH    BC
        PUSH    DE
        PUSH    HL

        ; 1. FETCH: Считываем знаковое смещение прыжка (imm8) через сквозной Fetch-шлюз
        ; Функция X86_Fetch_Byte сама переключит ОЗУ, заберет байт и сдвинет IP на инструкцию за LOOP
        CALL    X86_Fetch_Byte
        LD      C, A                    ; C = Считанное относительное смещение прыжка ($F9 / $FA)

        ; 2. Выполняем автоматический декремент счетчика CX без изменения флагов флагового регистра x86!
        LD      HL, (X86_REG_CX)
        DEC     HL
        LD      (X86_REG_CX), HL

        ; 3. ЧЕСТНАЯ ПРОВЕРКА РЕГИСТРА CX НА НОЛЬ ДЛЯ Z80
        LD      A, H                  
        OR      L                     
        JR      Z, .LoopEnd             ; Если CX стал равен 0 — цикл завершен, прыжка нет. Выходим!

        ; Вычисляем расширение знака смещения C в B для 16-битной математики Z80
        LD      B, 0
        BIT     7, C
        JR      Z, .Positive
        LD      B, $FF
.Positive:
        ; Прибавляем знаковое смещение к текущему IP (адресу возврата)
        LD      HL, (X86_REG_IP)
        ADD     HL, BC
        LD      (X86_REG_IP), HL        ; IP обновлен, процессор успешно переключился на начало цикла

.LoopEnd:
        POP     HL
        POP     DE
        POP     BC
        POP     AF
        RET                             ; Чистый возврат в главный цикл без порчи системных банок Хоста
