; -------------------------------------------------------------------------
; ВСПОМОГАТЕЛЬНАЯ ПРОЦЕДУРА: ОБНОВЛЕНИЕ ФЛАГОВ ДЛЯ СДВИГОВ
; Вход: HL = Результат операции, C = Значение флага Carry (0 или 1)
; -------------------------------------------------------------------------
Update_X86_Shift_Flags:
        PUSH    AF
        PUSH    BC
        
        LD      B, 0                 ; B будет копить флаги x86

        ; 1. Записываем вытолкнутый Carry Flag (Бит 0)
        LD      A, C
        AND     %00000001
        OR      B
        LD      B, A

        ; 2. Проверка Zero Flag (ZF - Бит 2)
        LD      A, H
        OR      L
        JR      NZ, .CheckSign
        SET     2, B                ; Если результат 0, взводим ZF

.CheckSign:
        ; 3. Проверка Sign Flag (SF - Бит 3, знаковый бит 15)
        BIT     7, H
        JR      Z, .SaveFlags
        SET     3, B                ; Если бит 15 равен 1, взводим SF

.SaveFlags:
        LD      A, B
        LD      (X86_REG_FLAGS), A   ; Записываем обновленный байт флагов x86
        
        POP     BC
        POP     AF
        RET

; -------------------------------------------------------------------------
; ОБРАБОТЧИК: SHL AX, 1 (Опкод $D1, $E0) -> Логический/Арифметический влево
; -------------------------------------------------------------------------
Op_SHL_AX_1:
        PUSH    HL
        PUSH    BC
        
        LD      HL, (X86_REG_AX)
        
        ; Определяем, какой бит уйдет в Carry (15-й бит HL)
        LD      C, 0
        BIT     7, H
        JR      Z, .DoShl
        LD      C, 1                 ; Старший бит равен 1, значит CF будет равен 1
        
.DoShl:
        ; Сдвигаем HL влево на Z80
        ADD     HL, HL              ; Сдвигает пару влево, младший бит заполняется 0
        
        LD      (X86_REG_AX), HL     ; Сохраняем результат в AX
        CALL    Update_X86_Shift_Flags
        
        POP     BC
        POP     HL
        RET

; -------------------------------------------------------------------------
; ОБРАБОТЧИК: SHR AX, 1 (Опкод $D1, $E8) -> Логический вправо (Заполнение 0)
; -------------------------------------------------------------------------
Op_Op_SHR_AX_1:
Op_SHR_AX_1:
        PUSH    HL
        PUSH    BC
        
        LD      HL, (X86_REG_AX)
        
        ; Определяем, какой бит уйдет в Carry (Младший бит 0 регистра L)
        LD      C, 0
        BIT     0, L
        JR      Z, .DoShr
        LD      C, 1
        
.DoShr:
        ; Побитовый сдвиг вправо 16-битной пары на Z80
        SRL     H                   ; Сдвигаем старший байт вправо, бит 7 заполняется 0
        RR      L                   ; Сдвигаем младший байт вправо через Carry Z80
        
        LD      (X86_REG_AX), HL     ; Сохраняем результат в AX
        CALL    Update_X86_Shift_Flags
        
        POP     BC
        POP     HL
        RET

; -------------------------------------------------------------------------
; ОБРАБОТЧИК: SAR AX, 1 (Опкод $D1, $F8) -> Арифметический вправо (Сохранение знака)
; -------------------------------------------------------------------------
Op_SAR_AX_1:
        PUSH    HL
        PUSH    BC
        
        LD      HL, (X86_REG_AX)
        
        ; Определяем, какой бит уйдет в Carry (Младший бит 0 регистра L)
        LD      C, 0
        BIT     0, L
        JR      Z, .DoSar
        LD      C, 1
        
.DoSar:
        ; Арифметический сдвиг вправо 16-битной пары на Z80 с удержанием знака
        SRA     H                   ; Арифметический сдвиг H (Знак в бите 7 сохраняется)
        RR      L                   ; Прокрутка L через Carry
        
        LD      (X86_REG_AX), HL     ; Сохраняем результат в AX
        CALL    Update_X86_Shift_Flags
        
        POP     BC
        POP     HL
        RET
