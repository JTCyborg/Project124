$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$BootstrapPath = Join-Path $Root 'neogs_bootstrap.bin'
$FirmwarePath = Join-Path $Root 'neogs_code.bin'
$PackagePath = Join-Path $Root 'neoprog.bin'
$HostPackagePath = Join-Path $Root 'zx_main/neoprog.bin'

foreach ($Path in @($BootstrapPath, $FirmwarePath)) {
    if (-not (Test-Path $Path -PathType Leaf)) {
        throw "Required NeoGS binary is missing: $Path"
    }
}

$Bootstrap = [IO.File]::ReadAllBytes($BootstrapPath)
$Firmware = [IO.File]::ReadAllBytes($FirmwarePath)

if ($Bootstrap.Length -eq 0 -or $Bootstrap.Length -gt 254) {
    throw "Invalid NeoGS bootstrap length: $($Bootstrap.Length) (maximum 254 bytes: 2-byte package header + bootstrap must fit in the first 256-byte TR-DOS sector)"
}
# Must match neogs_sub/build_firmware.asm and the runtime checks in
# neogs_sub/bootstrap.asm and zx_main/neogs_driver.asm.
# Firmware must fit below #3800; #3800-#3FFE is reserved for at least 2 KiB of Z80 stack
# in fixed WIN0. Keep this check aligned with build_firmware.asm's ASSERT.
if ($Firmware.Length -eq 0 -or $Firmware.Length -gt 0x3800) {
    throw "Invalid NeoGS firmware length: $($Firmware.Length) (maximum 14336 bytes / 0x3800)"
}

$PackageLength = 2 + $Bootstrap.Length + $Firmware.Length
# A TR-DOS file may contain up to 255 sectors (255 * 256 bytes).
# The Spectrum host no longer stores the whole package: the assembler places
# 16-KiB chunks into separate 128K RAM banks and appends them to one file.
if ($PackageLength -gt 0xFF00) {
    throw "NeoGS package exceeds the TR-DOS 255-sector limit: $PackageLength bytes"
}

# Package format consumed by the existing Stage 2 driver:
# [WORD bootstrap_length, little-endian][bootstrap][firmware]
$Package = New-Object byte[] $PackageLength
$Header = [BitConverter]::GetBytes([UInt16]$Bootstrap.Length)
[Array]::Copy($Header, 0, $Package, 0, 2)
[Array]::Copy($Bootstrap, 0, $Package, 2, $Bootstrap.Length)
[Array]::Copy($Firmware, 0, $Package, 2 + $Bootstrap.Length, $Firmware.Length)

[IO.File]::WriteAllBytes($PackagePath, $Package)
[IO.File]::WriteAllBytes($HostPackagePath, $Package)

# Split the single logical package into 16-KiB build chunks. These are
# assembly-time inputs only; the TR-DOS disk still contains one neoprog.C.
$ChunkSize = 0x4000
$ChunkCount = [int][Math]::Ceiling($PackageLength / [double]$ChunkSize)
$ChunkLines = @(
    "; Generated by pack_neogs.ps1. Do not edit manually."
    "NEOGS_PACKAGE_CHUNK_COUNT EQU $ChunkCount"
    "NEOGS_PACKAGE_TOTAL_SIZE EQU $PackageLength"
)
for ($Index = 0; $Index -lt 4; $Index++) {
    $ChunkPath = Join-Path $Root ("zx_main/neoprog_part{0}.bin" -f $Index)
    if ($Index -lt $ChunkCount) {
        $Offset = $Index * $ChunkSize
        $ChunkLength = [Math]::Min($ChunkSize, $PackageLength - $Offset)
        [byte[]]$Chunk = New-Object byte[] $ChunkLength
        [Array]::Copy($Package, $Offset, $Chunk, 0, $ChunkLength)
        [IO.File]::WriteAllBytes($ChunkPath, $Chunk)
        $ChunkLines += ("NEOGS_PACKAGE_CHUNK{0}_SIZE EQU {1}" -f $Index, $ChunkLength)
    }
    elseif (Test-Path -LiteralPath $ChunkPath) {
        Remove-Item -LiteralPath $ChunkPath -Force
    }
}
$ChunkIncludePath = Join-Path $Root 'zx_main/neoprog_chunks.inc'
[IO.File]::WriteAllLines($ChunkIncludePath, [string[]]$ChunkLines, [Text.Encoding]::ASCII)

Write-Host ("[PACK] neoprog.bin = {0} bytes (bootstrap {1} + firmware {2}); {3} TR-DOS chunk(s)" -f $PackageLength, $Bootstrap.Length, $Firmware.Length, $ChunkCount) -ForegroundColor Green
