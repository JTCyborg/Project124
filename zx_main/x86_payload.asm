        ; 1. Инструкция MOV AX, #BBAA
        ; Опкод: $B8, затем imm16 (сначала младший $AA, затем старший $BB)
        DEFB    #B8, #AA, #BB
        
        ; 2. Три инструкции INC AX для изменения значения
        ; Опкод: $40
        DEFB    #40                 ; AX = #BBAB
        DEFB    #40                 ; AX = #BBAC
        DEFB    #40                 ; AX = #BBAD
        
        ; 3. Инструкция NOP (Конец цепочки исполнения)
        ; Опкод: $90
        DEFB    #90
